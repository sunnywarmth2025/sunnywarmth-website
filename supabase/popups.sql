-- 首頁「彈出公告」資料表。只需要在 Supabase 的 SQL Editor 執行一次。
-- 權限與其他資料表一致：所有人可讀；寫入只限管理人員名單（public.is_admin()）。
create table if not exists public.popups (
  id          bigint generated by default as identity primary key,
  title       text        not null default '',
  image       text        not null default '',
  description text        not null default '',
  link        text        not null default '',
  button_text text        not null default '',
  start_at    timestamptz,
  end_at      timestamptz,
  enabled     boolean     not null default true,
  sort_order  integer     not null default 0,
  created_at  timestamptz not null default now()
);

alter table public.popups enable row level security;

drop policy if exists "popups 公開讀取" on public.popups;
create policy "popups 公開讀取" on public.popups
  for select using (true);

drop policy if exists "popups 管理人員寫入" on public.popups;
create policy "popups 管理人員寫入" on public.popups
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

grant select on public.popups to anon, authenticated;
grant insert, update, delete on public.popups to authenticated;
